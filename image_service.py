def _resolve_excel_color(color_obj, default_hex="000000") -> str:
    """Safely extracts a #RRGGBB hex color from an openpyxl Color object."""
    if not color_obj:
        return f"#{default_hex}"
    if color_obj.type == "rgb" and color_obj.rgb and len(str(color_obj.rgb)) >= 6:
        rgb = str(color_obj.rgb)[-6:]
        return f"#{rgb}"
    return f"#{default_hex}"


def _render_xlsx_with_openpyxl(excel_path: Path, png_path: Path, scale: float = 1.6) -> bool:
    """Renders the active worksheet of an .xlsx file into a crisp PNG using openpyxl + Pillow."""
    wb = openpyxl.load_workbook(str(excel_path), data_only=True)
    ws = wb.active

    # 1. Find true used bounds (ignoring trailing empty formatted columns/rows)
    used_max_r, used_max_c = 1, 1
    for r in range(1, (ws.max_row or 1) + 1):
        for c in range(1, (ws.max_column or 1) + 1):
            cell = ws.cell(r, c)
            has_val = cell.value is not None and str(cell.value).strip() != ""
            has_border = bool(
                cell.border and any([
                    cell.border.top and cell.border.top.style,
                    cell.border.bottom and cell.border.bottom.style,
                    cell.border.left and cell.border.left.style,
                    cell.border.right and cell.border.right.style,
                ])
            )
            if has_val or has_border:
                used_max_r = max(used_max_r, r)
                used_max_c = max(used_max_c, c)

    for m_range in ws.merged_cells.ranges:
        # Only include merged ranges that contain content or borders
        top_left = ws.cell(m_range.min_row, m_range.min_col)
        if (top_left.value is not None and str(top_left.value).strip() != "") or m_range.min_col <= used_max_c:
            used_max_r = max(used_max_r, m_range.max_row)
            used_max_c = max(used_max_c, m_range.max_col)

    for xl_img in getattr(ws, "_images", []):
        anchor = xl_img.anchor
        if hasattr(anchor, "to"):
            used_max_r = max(used_max_r, anchor.to.row + 1)
            used_max_c = max(used_max_c, anchor.to.col + 1)
        elif hasattr(anchor, "_from"):
            used_max_r = max(used_max_r, anchor._from.row + 1)
            used_max_c = max(used_max_c, anchor._from.col + 1)

    max_row, max_col = used_max_r, used_max_c

    # 2. Calculate pixel widths & heights
    col_widths_px = []
    for c in range(1, max_col + 1):
        col_letter = get_column_letter(c)
        w_chars = ws.column_dimensions[col_letter].width
        if w_chars is None:
            w_chars = 11.0
        col_widths_px.append(max(24, int((w_chars * 7.5 + 8) * scale)))

    row_heights_px = []
    for r in range(1, max_row + 1):
        h_pts = ws.row_dimensions[r].height
        if h_pts is None:
            h_pts = 18.0
        row_heights_px.append(max(18, int((h_pts * 1.35 + 4) * scale)))

    col_x = [0]
    for w in col_widths_px:
        col_x.append(col_x[-1] + w)

    row_y = [0]
    for h in row_heights_px:
        row_y.append(row_y[-1] + h)

    pad = int(16 * scale)
    img_w = col_x[-1] + pad * 2
    img_h = row_y[-1] + pad * 2

    img = PILImage.new("RGB", (img_w, img_h), (255, 255, 255))
    draw = ImageDraw.Draw(img)

    font_cache = {}
    def get_font(size_pt: float, bold: bool = False):
        px = max(10, int((size_pt or 10) * 1.3 * scale))
        key = (px, bold)
        if key not in font_cache:
            font_file = "arialbd.ttf" if bold else "arial.ttf"
            try:
                font_cache[key] = ImageFont.truetype(font_file, px)
            except Exception:
                font_cache[key] = ImageFont.load_default()
        return font_cache[key]

    # 3. Map merged cell ranges
    merged_lookup = {}
    skip_cells = set()
    for m_range in ws.merged_cells.ranges:
        merged_lookup[(m_range.min_row, m_range.min_col)] = (m_range.max_row, m_range.max_col)
        for r in range(m_range.min_row, m_range.max_row + 1):
            for c in range(m_range.min_col, m_range.max_col + 1):
                if (r, c) != (m_range.min_row, m_range.min_col):
                    skip_cells.add((r, c))

    # 4. Draw fills, borders, and cell text
    for r in range(1, max_row + 1):
        for c in range(1, max_col + 1):
            if (r, c) in skip_cells:
                continue

            end_r, end_c = merged_lookup.get((r, c), (r, c))
            end_r = min(end_r, max_row)
            end_c = min(end_c, max_col)

            x1 = pad + col_x[c - 1]
            y1 = pad + row_y[r - 1]
            x2 = pad + col_x[end_c]
            y2 = pad + row_y[end_r]

            cell = ws.cell(r, c)

            if cell.fill and cell.fill.fill_type == "solid":
                bg_hex = _resolve_excel_color(cell.fill.start_color, "FFFFFF")
                if bg_hex.upper() != "#000000":
                    draw.rectangle([x1, y1, x2, y2], fill=bg_hex)

            top_b = ws.cell(r, c).border.top if ws.cell(r, c).border else None
            left_b = ws.cell(r, c).border.left if ws.cell(r, c).border else None
            bottom_b = ws.cell(end_r, c).border.bottom if ws.cell(end_r, c).border else None
            right_b = ws.cell(r, end_c).border.right if ws.cell(r, end_c).border else None

            if top_b and top_b.style:
                draw.line([(x1, y1), (x2, y1)], fill="#334155", width=2 if top_b.style in ("thick", "medium") else 1)
            if bottom_b and bottom_b.style:
                draw.line([(x1, y2), (x2, y2)], fill="#334155", width=2 if bottom_b.style in ("thick", "medium") else 1)
            if left_b and left_b.style:
                draw.line([(x1, y1), (x1, y2)], fill="#334155", width=2 if left_b.style in ("thick", "medium") else 1)
            if right_b and right_b.style:
                draw.line([(x2, y1), (x2, y2)], fill="#334155", width=2 if right_b.style in ("thick", "medium") else 1)

            val = cell.value
            if val is not None and str(val).strip() != "":
                if isinstance(val, float):
                    text = f"{val:.3f}".rstrip("0").rstrip(".") if val % 1 != 0 else str(int(val))
                else:
                    text = str(val).strip()

                font = get_font(
                    cell.font.size if cell.font else 10,
                    bool(cell.font and cell.font.bold)
                )
                txt_color = _resolve_excel_color(cell.font.color if cell.font else None, "0F172A")
                if txt_color.upper() == "#FFFFFF" and (not cell.fill or cell.fill.fill_type != "solid"):
                    txt_color = "#0F172A"

                horiz = (cell.alignment.horizontal if cell.alignment else None) or ("right" if isinstance(val, (int, float)) else "left")
                vert = (cell.alignment.vertical if cell.alignment else None) or "center"

                bbox = draw.textbbox((0, 0), text, font=font)
                tw, th = bbox[2] - bbox[0], bbox[3] - bbox[1]
                margin = int(5 * scale)

                if horiz == "center":
                    tx = x1 + max(margin, (x2 - x1 - tw) // 2)
                elif horiz == "right":
                    tx = max(x1 + margin, x2 - tw - margin)
                else:
                    tx = x1 + margin

                if vert == "top":
                    ty = y1 + margin
                elif vert == "bottom":
                    ty = max(y1 + margin, y2 - th - margin)
                else:
                    ty = y1 + max(2, (y2 - y1 - th) // 2)

                draw.text((tx, ty), text, fill=txt_color, font=font)

    # 5. Paste embedded sketches using TwoCellAnchor bounds (prevents overlapping text)
    for xl_img in getattr(ws, "_images", []):
        try:
            anchor = xl_img.anchor
            if not hasattr(anchor, "_from"):
                continue

            c1 = min(anchor._from.col, max_col - 1)
            r1 = min(anchor._from.row, max_row - 1)
            ix = pad + col_x[c1] + int((anchor._from.colOff / 9525) * scale)
            iy = pad + row_y[r1] + int((anchor._from.rowOff / 9525) * scale)

            pil_embedded = PILImage.open(io.BytesIO(xl_img._data())).convert("RGBA")
            orig_w, orig_h = max(1, pil_embedded.width), max(1, pil_embedded.height)

            if hasattr(anchor, "to"):
                # Calculate exact target box from bottom-right anchor cell
                c2 = min(anchor.to.col, max_col - 1)
                r2 = min(anchor.to.row, max_row - 1)
                x2_box = pad + col_x[c2] + int((anchor.to.colOff / 9525) * scale)
                y2_box = pad + row_y[r2] + int((anchor.to.rowOff / 9525) * scale)
                box_w = max(20, x2_box - ix)
                box_h = max(20, y2_box - iy)

                # Fit proportionally inside the cell box so aspect ratio stays intact
                fit_ratio = min(box_w / orig_w, box_h / orig_h)
                iw = max(1, int(orig_w * fit_ratio))
                ih = max(1, int(orig_h * fit_ratio))
                ix += (box_w - iw) // 2
                iy += (box_h - ih) // 2
            else:
                iw = max(1, int(xl_img.width * scale))
                ih = max(1, int(xl_img.height * scale))

            pil_embedded = pil_embedded.resize((iw, ih), PILImage.Resampling.LANCZOS)
            img.paste(pil_embedded, (ix, iy), pil_embedded)
        except Exception:
            pass

    wb.close()
    img.save(png_path, format="PNG", optimize=True)
    return png_path.exists()


def get_or_render_biodata_png(style_code: str, excel_app=None) -> Optional[Path]:
    """
    Returns cached PNG path for a style's Biodata Excel.
    Uses fast pure-Python openpyxl rendering (~0.1s) with local PNG caching.
    """
    excel_path = find_biodata_excel_for_style(style_code)
    if not excel_path or not excel_path.exists():
        return None
    # If the matched biodata file is already a PNG/JPG/etc., return it directly without conversion
    if excel_path.suffix.lower() in SUPPORTED_EXTENSIONS:
        return excel_path

    os.makedirs(BIODATA_CACHE_DIR, exist_ok=True)
    safe_name = re.sub(r'[\\/*?:"<>|]', "_", str(style_code).strip())
    png_path = Path(BIODATA_CACHE_DIR) / f"{safe_name}.png"

