def get_image_source_for_style(style_code: str) -> str:
    """Categorizes style as 'primary' (500), 'secondary' (Sketch), or 'none' (Missing)."""
    q = str(style_code).strip().lower()
    if not q or q == "-":
        return "none"

    if q in _primary_index:
        return "primary"

    if find_image_for_style(style_code):
        return "secondary"

    return "none"

def index_image_directories():
    """Builds fast dictionary indexes of primary (500x500) and secondary (Sketch/LD) images."""
    global _primary_index, _fallback_index, _match_cache, _is_indexed

    os.makedirs(IMAGE_CACHE_DIR, exist_ok=True)
    _primary_index.clear()
    _fallback_index.clear()
    _match_cache.clear()

    # 1. Primary folder (500x500 - shallow scan)
    p_path = Path(PRIMARY_IMG_DIR)
    if p_path.exists():
        try:
            for entry in os.scandir(p_path):
                if entry.is_file() and Path(entry.name).suffix.lower() in SUPPORTED_EXTENSIONS:
                    stem = Path(entry.name).stem.strip().lower()
                    _primary_index[stem] = Path(entry.path)
            print(f"[INFO] Indexed {len(_primary_index):,} primary (500x500) images.")
        except Exception as e:
            print(f"[WARNING] Primary folder index error: {e}")

    # 2. Fallback folder (Secondary - Sketch / LD recursive scan)
    f_path = Path(FALLBACK_IMG_DIR)
    if f_path.exists():
        try:
            for root, _, files in os.walk(f_path):
                for f in files:
                    p = Path(f)
                    if p.suffix.lower() in SUPPORTED_EXTENSIONS:
                        full_path = Path(root) / f
                        stem = p.stem.strip().lower()

                        # A. Index exact stem
                        if stem not in _fallback_index:
                            _fallback_index[stem] = full_path

                        # B. Index cleaned stem without trailing spaces/dots/brackets
                        stem_clean = stem.rstrip(" ._()")
                        if stem_clean not in _fallback_index:
                            _fallback_index[stem_clean] = full_path

                        # C. Strip known prefixes (e.g., 'sketch_d1234' or 'sketch d1234' -> 'd1234')
                        for prefix in ["sketch_", "sketch ", "sketch-", "sketch", "ld_", "ld ", "ld-"]:
                            if stem.startswith(prefix):
                                stripped = stem[len(prefix):].strip(" ._()")
                                if stripped and stripped not in _fallback_index:
                                    _fallback_index[stripped] = full_path

                        # D. Split ONLY by underscores, spaces, and brackets (NEVER by hyphens '-')
                        # This preserves 'L-12345' while extracting it from 'SKETCH_L-12345_TOP.jpg'
                        tokens = re.split(r'[_ \t\(\)\[\]]+', stem)
                        for token in tokens:
                            token_clean = token.strip(" ._")
                            if token_clean and token_clean not in _fallback_index:
                                _fallback_index[token_clean] = full_path

            print(f"[INFO] Indexed {len(_fallback_index):,} secondary (Sketch) lookup keys.")
        except Exception as e:
            print(f"[WARNING] Secondary folder index error: {e}")

    # 3. CAD folder (Recursive scan with live progress & network stat caching)
    global _cad_file_list, _cad_index
    _cad_index.clear()
    _cad_file_list = []
    cad_path = Path(CAD_IMG_DIR)

    print(f"[INFO] Checking CAD folder connection: {CAD_IMG_DIR} ...")
    if cad_path.exists():
        print("[INFO] Connected to X:\\ drive successfully. Scanning CAD files...")
        try:
            raw_cad_files = []
            file_count = 0

            # Fast recursive scanner using os.scandir
            def fast_scan(dir_path):
                nonlocal file_count
                try:
                    with os.scandir(dir_path) as it:
                        for entry in it:
                            if entry.is_file(follow_symlinks=False):
                                ext = os.path.splitext(entry.name)[1].lower()
                                if ext in SUPPORTED_EXTENSIONS:
                                    stem = os.path.splitext(entry.name)[0].strip().lower()
                                    # entry.stat() is cached by Windows SMB - zero extra network calls!
                                    try:
                                        mtime = entry.stat().st_mtime
                                    except Exception:
                                        mtime = 0.0
                                    raw_cad_files.append((stem, Path(entry.path), mtime))
                                    file_count += 1
                                    
                            elif entry.is_dir(follow_symlinks=False):
                                fast_scan(entry.path)
                except (PermissionError, OSError):
                    pass

            fast_scan(str(cad_path))
            print(f"[INFO] Total CAD files found: {file_count:,}. Sorting by latest date...")

            # Sort descending by mtime
            raw_cad_files.sort(key=lambda x: x[2], reverse=True)
            _cad_file_list = raw_cad_files

            # Pre-index exact stems, tokens, and right-trimmed style numbers (newest modified takes priority)
            for stem, full_p, mtime in _cad_file_list:
                if stem not in _cad_index:
                    _cad_index[stem] = full_p

                # Split by space, underscore, brackets (NEVER by hyphen '-')
                tokens = re.split(r'[_ \t\(\)\[\]]+', stem)
                for t in tokens:
                    t_clean = t.strip(" ._")
                    if t_clean:
                        if t_clean not in _cad_index:
                            _cad_index[t_clean] = full_p

                        # Strip trailing suffix segments (e.g. 'br-59871-100-ma' -> 'br-59871-100')
                        cur_str = t_clean
                        while '-' in cur_str:
                            cur_str = cur_str.rsplit('-', 1)[0].strip(" ._")
                            if cur_str and cur_str not in _cad_index:
                                _cad_index[cur_str] = full_p

            print(f"[INFO] Indexed {len(_cad_file_list):,} CAD photos (sorted by latest modified date).")
        except Exception as e:
            print(f"[WARNING] CAD folder index error: {e}")
    else:
        print(f"[WARNING] CAD directory not accessible: {CAD_IMG_DIR}")
    
    # 4. Biodata Excel & Image folder scan (Excel priority, PNG/JPG fallback)
    global _biodata_index, _biodata_img_index
    os.makedirs(BIODATA_CACHE_DIR, exist_ok=True)
    _biodata_index.clear()
    _biodata_img_index.clear()
    bio_path = Path(BIODATA_EXCEL_DIR)

    def _build_suffix_index(file_entries: List[tuple], target_dict: Dict[str, Path]):
        # Sort newest modified date first so latest version (e.g., (2) over (1)) wins
        file_entries.sort(key=lambda x: x[2], reverse=True)

        # Pass 1: Exact stems & duplicate-number stems like 'STYLE (1)' take highest priority
        for stem, full_p, _ in file_entries:
            if stem not in target_dict:
                target_dict[stem] = full_p
            no_dup = re.sub(r'\s*\(\d+\)$', '', stem).strip(" ._")
            if no_dup and no_dup not in target_dict:
                target_dict[no_dup] = full_p

        # Pass 2: Strip trailing suffixes (_MB, -MB, (1), etc.) from right to left
        for stem, full_p, _ in file_entries:
            tokens = re.split(r'[_ \t\(\)\[\]]+', stem)
            for t in tokens:
                t_clean = t.strip(" ._")
                if not t_clean:
                    continue
                if t_clean not in target_dict:
                    target_dict[t_clean] = full_p

                cur_str = t_clean
                while '-' in cur_str:
                    cur_str = cur_str.rsplit('-', 1)[0].strip(" ._")
                    if cur_str and cur_str not in target_dict:
                        target_dict[cur_str] = full_p

    print(f"[INFO] Checking Biodata folder connection: {BIODATA_EXCEL_DIR} ...")
    if bio_path.exists():
        print("[INFO] Connected to Biodata folder. Scanning Excel and image files recursively...")
        try:
            raw_bio_excels = []
            raw_bio_imgs = []

            def fast_bio_scan(dir_path):
                try:
                    with os.scandir(dir_path) as it:
                        for entry in it:
                            if entry.is_file(follow_symlinks=False):
                                if entry.name.startswith("~$"):
                                    continue
                                ext = os.path.splitext(entry.name)[1].lower()
                                stem = os.path.splitext(entry.name)[0].strip().lower()
                                try:
                                    mtime = entry.stat().st_mtime
                                except Exception:
                                    mtime = 0.0

                                if ext in {".xlsx", ".xls", ".xlsm"}:
                                    raw_bio_excels.append((stem, Path(entry.path), mtime))
                                elif ext in SUPPORTED_EXTENSIONS:
                                    raw_bio_imgs.append((stem, Path(entry.path), mtime))
                            elif entry.is_dir(follow_symlinks=False):
                                fast_bio_scan(entry.path)
                except (PermissionError, OSError):
                    pass

            fast_bio_scan(str(bio_path))
            _build_suffix_index(raw_bio_excels, _biodata_index)
            _build_suffix_index(raw_bio_imgs, _biodata_img_index)
            print(
                f"[SUCCESS] Biodata scan complete! Indexed {len(raw_bio_excels):,} Excels "
                f"and {len(raw_bio_imgs):,} fallback images."
            )
        except Exception as e:
            print(f"[ERROR] Biodata folder scan failed: {e}")
    else:
        print(f"[WARNING] Biodata directory NOT accessible: {BIODATA_EXCEL_DIR}")
    _is_indexed = True


def find_image_for_style(style_code: str) -> Optional[Path]:
    global _is_indexed
    if not _is_indexed:
        index_image_directories()

    q = str(style_code).strip().lower()
    if not q or q == "-":
        return None

    if q in _match_cache:
        return _match_cache[q]

    # Priority 1: Exact match in 500x500 (Primary)
    if q in _primary_index:
        res = _primary_index[q]
        _match_cache[q] = res
        return res

    # Priority 2: Match in Secondary (Sketch) dictionary
    if q in _fallback_index:
        res = _fallback_index[q]
        _match_cache[q] = res
        return res

    # Priority 3: Fallback without 'L-' prefix if user code has it
    if q.startswith("l-") and q[2:] in _fallback_index:
        res = _fallback_index[q[2:]]
        _match_cache[q] = res
        return res

    _match_cache[q] = None
    return None

